global.window = globalThis;
await import('../qbank-data.js');

const raw = window.QBANK;
const domain = p => p.topic === 'counting2' ? 'counting' : p.topic;
const usable = p => !p.img && String(p.text || '').length >= 60 &&
  !!String(p.ans || '').trim() && (!p.mc || /^[A-E]$/i.test(String(p.ans)));

function move(p) {
  const t = String(p.text || '').toLowerCase();
  const d = domain(p);
  if (d === 'geometry') {
    if (/coordinate|\([\d-]+,\s*[\d-]+\)|x-axis|y-axis|vector/.test(t)) return 'Coordinates / vectors';
    if (/circle|tangent|incircle|circumcircle|arc|chord/.test(t)) return 'Circles / tangency';
    if (/cube|sphere|tetra|cone|pyramid|solid|volume|plane/.test(t)) return '3D visualization';
    if (/similar|ratio|midpoint|median|area|parallel/.test(t)) return 'Similarity / area ratios';
    return 'Hidden construction';
  }
  if (d === 'algebra') {
    if (/polynomial|root|factor|remainder|coefficient|cubic/.test(t)) return 'Polynomial structure';
    if (/sequence|recurr|term|arithmetic|geometric/.test(t)) return 'Recurrence / sequence';
    if (/absolute|\|x|floor|ceiling|piecewise|function/.test(t)) return 'Functions / casework';
    if (/quadratic|parabola|system|equation/.test(t)) return 'Equation modeling';
    return 'Algebraic transformation';
  }
  if (d === 'number') {
    if (/mod|remainder|congruen|last digit|base-|binary|decimal digit/.test(t)) return 'Modular / digit structure';
    if (/divisor|divisible|factor|multiple|gcd|lcm/.test(t)) return 'Divisibility / factors';
    if (/integer pair|lattice|positive integer|diophant/.test(t)) return 'Integer modeling';
    if (/prime/.test(t)) return 'Prime structure';
    return 'Invariant / process';
  }
  if (/probability|random|uniform|chosen|coin|dice|die/.test(t)) return 'Probability / complement';
  if (/path|graph|color|vertex|edge|friend/.test(t)) return 'Graph / path states';
  if (/permutation|arrang|order|sequence/.test(t)) return 'Permutations / constraints';
  if (/subset|set|inclusion|at least|none/.test(t)) return 'Inclusion–exclusion';
  return 'Case split / recurrence';
}

function score(p) {
  let s = p.stage === 'amc_mid' ? 8 : 0;
  s += p.band === 'olympiad' ? 6 : p.band === 'expert' ? 4 : 0;
  s += p.sol ? 2 : 0;
  s += /verified|source_resolved|pdf_resolved/.test(p.answer_status || '') ? 2 : 0;
  s -= Math.abs(Number(p.diff || 0) - 5);
  return s;
}

const textKey = p => String(p.text || '').toLowerCase().replace(/\s+/g, '').replace(/[^a-z0-9]/g, '');
const quota = {geometry: 90, number: 75, counting: 78, algebra: 57};
const anchors = raw.filter(p => usable(p) && p.stage === 'amc_last5');
const selected = [...anchors];
const used = new Set(selected.map(p => p.canonical_id));
const usedText = new Set(selected.map(textKey));

for (const d of Object.keys(quota)) {
  const have = selected.filter(p => domain(p) === d).length;
  const pool = raw.filter(p => usable(p) && p.stage !== 'amc_last5' && domain(p) === d &&
    ['hard', 'expert', 'olympiad'].includes(p.band) && !used.has(p.canonical_id));
  pool.sort((a, b) => score(b) - score(a) || Number(b.diff) - Number(a.diff) ||
    Number(a.canonical_id) - Number(b.canonical_id));
  let need = quota[d] - have;
  for (const p of pool) {
    if (!need) break;
    const key = textKey(p);
    if (usedText.has(key)) continue;
    selected.push(p);
    used.add(p.canonical_id);
    usedText.add(key);
    need--;
  }
}

if (selected.length !== 300) throw new Error(`Expected 300, got ${selected.length}`);

const rank = p => p.stage === 'amc_last5' ? 2 : Number(p.diff) >= 5 ? 1 : 0;
const level = p => ['Bridge', 'Target', 'Benchmark'][rank(p)];
const buckets = Object.fromEntries(Object.keys(quota).map(d => [d,
  selected.filter(p => domain(p) === d).sort((a, b) => rank(a) - rank(b) ||
    Number(a.diff) - Number(b.diff) || Number(a.canonical_id) - Number(b.canonical_id))]));

const order = [];
const cycle = ['geometry', 'counting', 'number', 'algebra'];
while (order.length < 300) {
  for (const d of cycle) if (buckets[d].length) order.push(buckets[d].shift());
}

const output = order.map((p, index) => ({
  id: p.id,
  canonical_id: p.canonical_id,
  sprint_order: index + 1,
  sprint_domain: domain(p),
  sprint_level: level(p),
  sprint_move: move(p),
  is_benchmark: p.stage === 'amc_last5'
}));

const meta = {
  generated_from: 'qbank-data.js',
  total: output.length,
  quota,
  benchmark_count: output.filter(x => x.is_benchmark).length,
  transfer_count: output.filter(x => !x.is_benchmark).length,
  selection_rule: 'All usable AMC10 last-five benchmarks plus highest-scoring non-last-five hard/expert/olympiad transfer problems, balanced to the audited 2010–2019 late-problem domain mix.'
};

const js = `// Generated by scripts/build-sprint300.mjs.\nwindow.SPRINT300_META = ${JSON.stringify(meta)};\nwindow.SPRINT300 = ${JSON.stringify(output)};\n`;
await Bun.write('./sprint300-data.js', js);
console.log(JSON.stringify(meta, null, 2));

